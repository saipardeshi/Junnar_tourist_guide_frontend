/* global process */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const BASE_URL = process.env.SITE_URL || "https://junnar-tourist-guide-frontend.vercel.app";
const API_URL = process.env.VITE_API_URL || "https://junnar-tourist-guide-backend.onrender.com/api";

// Render's free tier can take ~50s to wake up, so don't give up too early.
const FETCH_TIMEOUT_MS = Number(process.env.SITEMAP_FETCH_TIMEOUT_MS) || 60000;

const STATIC_ROUTES = [
  { path: "", priority: "1.0", changefreq: "daily" },
  { path: "/places", priority: "0.9", changefreq: "weekly" },
  { path: "/map", priority: "0.9", changefreq: "weekly" },
  { path: "/hotels", priority: "0.8", changefreq: "weekly" },
  { path: "/experiences", priority: "0.8", changefreq: "weekly" },
  { path: "/events", priority: "0.8", changefreq: "weekly" },
  { path: "/ai-planner", priority: "0.8", changefreq: "monthly" },
  { path: "/cost", priority: "0.7", changefreq: "monthly" },
  { path: "/tips", priority: "0.7", changefreq: "monthly" },
  { path: "/contact", priority: "0.6", changefreq: "monthly" },
  { path: "/privacy", priority: "0.3", changefreq: "yearly" },
  { path: "/terms", priority: "0.3", changefreq: "yearly" },
];

// Place IDs are generated by MongoDB, so they can't be guessed or hard-coded.
// If the backend can't be reached we emit the static pages only: a sitemap with
// fewer URLs is harmless, one full of made-up place URLs would be indexed as 404s.
async function fetchPlaceIds() {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), FETCH_TIMEOUT_MS);
  try {
    const res = await fetch(`${API_URL}/places`, { signal: controller.signal });
    if (!res.ok) throw new Error(`HTTP error ${res.status}`);
    const data = await res.json();
    if (!Array.isArray(data)) throw new Error("unexpected response shape");
    return data.map((p) => p.id || p._id).filter(Boolean);
  } catch (err) {
    console.warn(
      `⚠️ Could not fetch places from ${API_URL} (${err.message}). ` +
      `Generating the sitemap with static pages only - place pages will be added on the next successful build.`
    );
    return [];
  } finally {
    clearTimeout(timeout);
  }
}

async function generateSitemap() {
  const today = new Date().toISOString().split("T")[0];
  const placeIds = await fetchPlaceIds();

  let xml = `<?xml version="1.0" encoding="UTF-8"?>\n`;
  xml += `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n`;

  // Static routes
  for (const route of STATIC_ROUTES) {
    xml += `  <url>\n`;
    xml += `    <loc>${BASE_URL}${route.path}</loc>\n`;
    xml += `    <lastmod>${today}</lastmod>\n`;
    xml += `    <changefreq>${route.changefreq}</changefreq>\n`;
    xml += `    <priority>${route.priority}</priority>\n`;
    xml += `  </url>\n`;
  }

  // Dynamic place routes
  for (const id of placeIds) {
    xml += `  <url>\n`;
    xml += `    <loc>${BASE_URL}/places/${encodeURIComponent(id)}</loc>\n`;
    xml += `    <lastmod>${today}</lastmod>\n`;
    xml += `    <changefreq>weekly</changefreq>\n`;
    xml += `    <priority>0.8</priority>\n`;
    xml += `  </url>\n`;
  }

  xml += `</urlset>\n`;

  const publicDir = path.resolve(__dirname, "../public");
  if (!fs.existsSync(publicDir)) {
    fs.mkdirSync(publicDir, { recursive: true });
  }

  const sitemapPath = path.join(publicDir, "sitemap.xml");
  fs.writeFileSync(sitemapPath, xml, "utf-8");
  console.log(`✅ Sitemap successfully written to ${sitemapPath} (${STATIC_ROUTES.length + placeIds.length} URLs)`);
}

generateSitemap();
